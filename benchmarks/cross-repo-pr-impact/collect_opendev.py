GITEA = "https://opendev.org"
QUERY = 'message:"Depends-On:" status:merged'
DEPENDS_RE = re.compile(
    r"^[ \t]*depends-on:[ \t]*"
    r"(https://review\.opendev\.org/(?:#/c/|c/(?:[^/\s]+/)+\+/)?(\d+))"
    r"[ \t]*$",
    re.IGNORECASE | re.MULTILINE,
)
BUILDSET_RE = re.compile(r"https://zuul\.opendev\.org/[^\s]+/buildset/[0-9a-f]+")
META_FILES = {"/COMMIT_MSG", "/MERGE_LIST"}


class CollectionError(RuntimeError):
    pass


def request_bytes(url: str, attempts: int = 4) -> bytes:
    request = urllib.request.Request(
        url,
        headers={"User-Agent": "marshal-cross-repo-benchmark/1.0"},
    )
    for attempt in range(attempts):
        try:
            with urllib.request.urlopen(request, timeout=45) as response:
                return response.read()
        except (urllib.error.URLError, TimeoutError) as exc:
            if attempt + 1 == attempts:
                raise CollectionError(f"request failed: {url}: {exc}") from exc
            time.sleep(1.5 * (attempt + 1))
    raise AssertionError("unreachable")


def gerrit_json(path: str, params: list[tuple[str, str]] | None = None) -> Any:
    query = urllib.parse.urlencode(params or [])
    url = f"{GERRIT}{path}" + (f"?{query}" if query else "")
    payload = request_bytes(url).decode("utf-8")
    if payload.startswith(")]}'"):
        payload = payload.split("\n", 1)[1]
    return json.loads(payload)


def current_revision(change: dict[str, Any]) -> tuple[str, dict[str, Any]]:
    revision = change.get("current_revision")
    revisions = change.get("revisions", {})
    if not revision or revision not in revisions:
        raise CollectionError(f"change {change.get('_number')} has no current revision")
    return revision, revisions[revision]


def changed_paths(files: dict[str, Any]) -> list[str]:
    return sorted(path for path in files if path not in META_FILES)


def fetch_change(number: int) -> dict[str, Any]:
    detail = gerrit_json(
        f"/changes/{number}/detail",
        [("o", "CURRENT_REVISION"), ("o", "CURRENT_COMMIT")],
    )
    files = gerrit_json(f"/changes/{number}/revisions/current/files/")
    revision, revision_data = current_revision(detail)
    commit = revision_data.get("commit", {})
    parents = commit.get("parents", [])
    if not parents:
        raise CollectionError(f"change {number} has no parent commit")
    return {
        "detail": detail,
        "revision": revision,
        "commit": commit,
        "base_commit": parents[0]["commit"],
        "paths": changed_paths(files),
    }


def query_dependent_changes(max_pages: int) -> list[dict[str, Any]]:
    changes: list[dict[str, Any]] = []
    for page in range(max_pages):
        batch = gerrit_json(
            "/changes/",
            [
                ("q", QUERY),
                ("n", "500"),
                ("S", str(page * 500)),
                ("o", "CURRENT_REVISION"),
                ("o", "CURRENT_COMMIT"),
            ],
        )
        changes.extend(batch)
        if not batch or not batch[-1].get("_more_changes"):
            break
    return changes


def review_record(change: dict[str, Any]) -> dict[str, Any]:
    submitted = change.get("submitted")
    created = change.get("created")
    if not submitted:
        raise CollectionError(f"change {change.get('_number')} has no submitted timestamp")
    if not created:
        raise CollectionError(f"change {change.get('_number')} has no created timestamp")
    return {
        "provider": "gerrit",
        "number": int(change["_number"]),
        "change_id": change["change_id"],
        "url": f"{GERRIT}/c/{change['project']}/+/{change['_number']}",
        "status": change["status"],
        "subject": change["subject"],
        "branch": change["branch"],
        "created": created,
        "submitted": submitted,
    }


def gate_buildset(change: dict[str, Any]) -> str | None:
    for message in reversed(change.get("messages", [])):
        if message.get("tag") != "autogenerated:zuul:gate":
            continue
        if "Build succeeded" not in message.get("message", ""):
            continue
        match = BUILDSET_RE.search(message["message"])
        if match:
            return match.group(0)
    return None


def verified(change: dict[str, Any]) -> bool:
    label = change.get("labels", {}).get("Verified", {})
    approved = label.get("approved")
    if approved:
        return True
    return any(
        item.get("label") == "Verified" and item.get("status") in {"OK", "MAY"}
        for record in change.get("submit_records", [])
        for item in record.get("labels", [])
    )


def detect_license(repository: str, commit: str) -> dict[str, str]:
    candidates = ("LICENSE", "LICENSE.txt", "COPYING", "COPYING.txt")
    for filename in candidates:
        url = f"{GITEA}/{repository}/raw/commit/{commit}/{filename}"
        try:
            text = request_bytes(url, attempts=2).decode("utf-8", errors="replace")
        except CollectionError:
            continue
        lowered = text.lower()
        if "apache license" in lowered and "version 2.0" in lowered:
            spdx = "Apache-2.0"
        elif "permission is hereby granted, free of charge" in lowered:
            spdx = "MIT"
        elif "mozilla public license version 2.0" in lowered:
            spdx = "MPL-2.0"
        elif "gnu general public license" in lowered and "version 3" in lowered[:1000]:
            spdx = "GPL-3.0-only"
        elif "gnu general public license" in lowered and "version 2" in lowered[:1000]:
            spdx = "GPL-2.0-only"
        elif "redistribution and use in source and binary forms" in lowered:
            spdx = "BSD-3-Clause"
        else:
            spdx = "NOASSERTION"
        return {"repository": repository, "spdx": spdx, "evidence_url": url}
    return {
        "repository": repository,
        "spdx": "NOASSERTION",
        "evidence_url": f"{GITEA}/{repository}/src/commit/{commit}",
    }


def make_target(source: dict[str, Any], target: dict[str, Any], statement_url: str) -> dict[str, Any]:
    detail = target["detail"]
    buildset = gate_buildset(detail)
    statement = f"Depends-On: {statement_url}"
    return {
        "repository": detail["project"],
        "pull_request": review_record(detail),
        "commit": target["revision"],
        "changed_paths": target["paths"],
        "label_scope": "known_coordination",
        "impact_kind": "unclassified",
        "impact_kind_source": "unclassified",
        "expected_checks": {
            "label_kind": "unavailable",
            "paths": [],
            "symbols": [],
            "tests": [],
            "commands": [],
            "expected_result": "coordination_observed",
        },
        "evidence": [
            {
                "level": "coordination_proven",
                "kind": "depends_on_trailer_and_merged_change",
                "url": review_record(detail)["url"],
                "statement": statement,
                "ci_url": buildset if buildset and verified(detail) else None,
            }
        ],
    }


def raw_candidate_frame(
    dependents: list[dict[str, Any]],
    raw_links: list[tuple[int, int, str]],
) -> list[dict[str, Any]]:
    """Collapse the full query result into chain-independent source candidates."""
    by_number = {int(change["_number"]): change for change in dependents}
    outgoing: dict[int, set[int]] = {}
    graph: dict[int, set[int]] = {}
    for source_number, target_number, _ in raw_links:
        outgoing.setdefault(source_number, set()).add(target_number)
        graph.setdefault(source_number, set()).add(target_number)
        graph.setdefault(target_number, set()).add(source_number)

    components = []
    unseen = set(graph)
    while unseen:
        seed = unseen.pop()
        component = {seed}
        queue = [seed]
        while queue:
            current = queue.pop()
            neighbors = graph[current] & unseen
            unseen.difference_update(neighbors)
            component.update(neighbors)
            queue.extend(neighbors)
        components.append(component)

    frame = []
    for component in components:
        source_numbers = component & outgoing.keys()
        if not source_numbers:
            continue

        def submitted_hint(number: int) -> str:
            change = by_number.get(number)
            if change and change.get("submitted"):
                return change["submitted"]
            target_dates = [
                by_number[target].get("submitted", "")
                for target in outgoing[number]
                if target in by_number
            ]
            return min(target_dates, default="")

        if 1001388 in source_numbers:
            representative = 1001388
        else:
            representative = max(
                source_numbers,
                key=lambda number: (len(outgoing[number]), submitted_hint(number), number),
            )
        frame.append({
            "source_pr": representative,
            "target_prs": sorted(outgoing[representative]),
            "submitted_hint": submitted_hint(representative),
            "component_size": len(component),
        })
    return sorted(frame, key=lambda item: (item["submitted_hint"], item["source_pr"]))


def sample_frame(
    frame: list[dict[str, Any]],
    count: int,
    required_source_numbers: set[int],
) -> list[dict[str, Any]]:
    by_source = {item["source_pr"]: item for item in frame}
    missing = required_source_numbers - by_source.keys()
    if missing:
        raise CollectionError(f"required source changes missing from query frame: {sorted(missing)}")
    required = [by_source[number] for number in sorted(required_source_numbers)]
    remaining = [item for item in frame if item["source_pr"] not in required_source_numbers]
    slots = min(count - len(required), len(remaining))
    sampled = []
    for index in range(slots):
        position = ((2 * index + 1) * len(remaining)) // (2 * slots) if slots else 0
        sampled.append(remaining[position])
    return required + sampled


def collect_candidates(
    max_pages: int,
    fetch_count: int,
) -> tuple[list[dict[str, Any]], Counter[str], list[dict[str, Any]], int]:
    dependents = query_dependent_changes(max_pages)
    raw_links: list[tuple[int, int, str]] = []
    for dependent in dependents:
        try:
            _, revision_data = current_revision(dependent)
        except CollectionError:
            continue
        message = revision_data.get("commit", {}).get("message", "")
        for match in DEPENDS_RE.finditer(message):
            raw_links.append((int(match.group(2)), int(dependent["_number"]), match.group(1)))

    frame = raw_candidate_frame(dependents, raw_links)
    sampled_frame = sample_frame(frame, fetch_count, {1001388})
    sampled_source_numbers = {item["source_pr"] for item in sampled_frame}
    sampled_links = [link for link in raw_links if link[0] in sampled_source_numbers]
    numbers = sorted({number for link in sampled_links for number in link[:2]})
    fetched: dict[int, dict[str, Any]] = {}
    rejected: Counter[str] = Counter()
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as executor:
        futures = {executor.submit(fetch_change, number): number for number in numbers}
        for future in concurrent.futures.as_completed(futures):
            number = futures[future]
            try:
                fetched[number] = future.result()
            except Exception:
                rejected["fetch_failed"] += 1

    grouped: dict[int, dict[str, Any]] = {}
    seen_links: set[tuple[int, int]] = set()
    for source_number, target_number, statement_url in sampled_links:
        if (source_number, target_number) in seen_links:
            continue
        seen_links.add((source_number, target_number))
        source = fetched.get(source_number)
        target = fetched.get(target_number)
        if not source or not target:
            rejected["missing_change"] += 1
            continue
        source_detail = source["detail"]
        target_detail = target["detail"]
        if source_detail.get("status") != "MERGED" or target_detail.get("status") != "MERGED":
            rejected["not_both_merged"] += 1
            continue
        if source_detail["project"] == target_detail["project"]:
            rejected["same_repository"] += 1
            continue
        if not source["paths"] or not target["paths"]:
            rejected["no_changed_paths"] += 1
            continue

        case = grouped.get(source_number)
        if case is None:
            source_repo = source_detail["project"]
            case = {
                "schema_version": "1.1",
                "case_id": f"opendev-{source_number}",
                "project": source_repo.split("/", 1)[0],
                "split": "test",
                "case_kind": "independent_positive",
                "source": {
                    "host": "review.opendev.org",
                    "repository": source_repo,
                    "pull_request": review_record(source_detail),
                    "base_commit": source["base_commit"],
                    "candidate_commit": source["revision"],
                    "changed_paths": source["paths"],
                    "patch_url": f"{GERRIT}/changes/{source_number}/revisions/{source['revision']}/patch",
                },
                "relations": [],
                "targets": [],
                "label_source": {
                    "kind": "independent_project_evidence",
                    "derived_from_marshal_config": False,
                },
                "licenses": [],
                "provenance": {
                    "collector": "collect_opendev.py",
                    "collected_at": dt.date.today().isoformat(),
                    "query": QUERY,
                },
            }
            grouped[source_number] = case

        target_repo = target_detail["project"]
        if any(item["pull_request"]["number"] == target_number for item in case["targets"]):
            continue
        case["relations"].append(
            {
                "source_repository": source_detail["project"],
                "target_repository": target_repo,
                "relation_kind": "explicit_depends_on",
                "evidence_url": review_record(target_detail)["url"],
            }
        )
        case["targets"].append(make_target(source, target, statement_url))

    return list(grouped.values()), rejected, frame, len({link[0] for link in raw_links})


def change_numbers(case: dict[str, Any]) -> set[int]:
    return {
        case["source"]["pull_request"]["number"],
        *(target["pull_request"]["number"] for target in case["targets"]),
    }


def deduplicate_change_chains(cases: list[dict[str, Any]]) -> tuple[list[dict[str, Any]], int]:
    """Keep one representative source from each connected Depends-On chain."""
    remaining = {case["case_id"]: case for case in cases}
    components: list[list[dict[str, Any]]] = []
    while remaining:
        _, seed = remaining.popitem()
        component = [seed]
        numbers = change_numbers(seed)
        changed = True
        while changed:
            changed = False
            for case_id, case in list(remaining.items()):
                if numbers & change_numbers(case):
                    component.append(case)
                    numbers.update(change_numbers(case))
                    del remaining[case_id]
                    changed = True
        components.append(component)

    representatives = []
    for component in components:
        representatives.append(max(
            component,
            key=lambda case: (
                len(case["targets"]),
                case["source"]["pull_request"]["submitted"],
                case["case_id"],
            ),
        ))
    representatives.sort(key=lambda case: case["source"]["pull_request"]["submitted"])
    return representatives, len(cases) - len(representatives)


def systematic_sample(
    cases: list[dict[str, Any]],
    count: int,
    required_case_ids: set[str] | None = None,
) -> list[dict[str, Any]]:
    """Sample the full time-ordered frame without favoring one-case source repositories."""
    required_case_ids = required_case_ids or set()
    by_id = {case["case_id"]: case for case in cases}
    missing = required_case_ids - by_id.keys()
    if missing:
        raise CollectionError(f"required cases missing from candidate frame: {sorted(missing)}")
    if count > len(cases):
        raise CollectionError(f"only {len(cases)} chain-independent candidates, need {count}")
    required = [by_id[case_id] for case_id in sorted(required_case_ids)]
    remaining = [case for case in cases if case["case_id"] not in required_case_ids]
    slots = count - len(required)
    if slots < 0:
        raise CollectionError("required cases exceed requested sample size")
    sampled = []
    for index in range(slots):
        position = ((2 * index + 1) * len(remaining)) // (2 * slots) if slots else 0
        sampled.append(remaining[position])
    return sorted(required + sampled, key=lambda case: case["source"]["pull_request"]["submitted"])


