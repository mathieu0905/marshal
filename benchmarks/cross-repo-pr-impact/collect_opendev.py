def attach_licenses(cases: list[dict[str, Any]]) -> dict[str, dict[str, str]]:
    refs: dict[str, str] = {}
    for case in cases:
        refs.setdefault(case["source"]["repository"], case["source"]["candidate_commit"])
        for target in case["targets"]:
            refs.setdefault(target["repository"], target["commit"])
    licenses: dict[str, dict[str, str]] = {}
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as executor:
        futures = {
            executor.submit(detect_license, repository, commit): repository
            for repository, commit in refs.items()
        }
        for future in concurrent.futures.as_completed(futures):
            repository = futures[future]
            licenses[repository] = future.result()
    for case in cases:
        repositories = {case["source"]["repository"]}
        repositories.update(target["repository"] for target in case["targets"])
        case["licenses"] = [licenses[repository] for repository in sorted(repositories)]
    return licenses


def write_dataset(
    cases: list[dict[str, Any]],
    licenses: dict[str, dict[str, str]],
    rejected: Counter[str],
    candidate_frame: list[dict[str, Any]],
    chain_duplicates: int,
    raw_source_candidates: int,
) -> None:
    cases_dir = ROOT / "cases"
    cases_dir.mkdir(exist_ok=True)
    for old in cases_dir.glob("*.json"):
        old.unlink()
    for case in cases:
        path = cases_dir / f"{case['case_id']}.json"
        path.write_text(json.dumps(case, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    with (ROOT / "index.jsonl").open("w", encoding="utf-8") as handle:
        for case in cases:
            record = {
                "case_id": case["case_id"],
                "path": f"cases/{case['case_id']}.json",
                "project": case["project"],
                "split": case["split"],
                "case_kind": case["case_kind"],
                "source_repository": case["source"]["repository"],
                "source_pr": case["source"]["pull_request"]["number"],
                "target_repositories": sorted({target["repository"] for target in case["targets"]}),
            }
            handle.write(json.dumps(record, ensure_ascii=False, sort_keys=True) + "\n")

    with (ROOT / "candidate-pool.jsonl").open("w", encoding="utf-8") as handle:
        for record in candidate_frame:
            handle.write(json.dumps(record, ensure_ascii=False, sort_keys=True) + "\n")

    candidate_repositories = sorted({
        repository
        for case in cases
        for repository in [
            case["source"]["repository"],
            *(target["repository"] for target in case["targets"]),
        ]
    })
    (ROOT / "candidate-repositories.json").write_text(
        json.dumps({
            "schema_version": "1.0",
            "repositories": candidate_repositories,
        }, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    with (ROOT / "inputs.jsonl").open("w", encoding="utf-8") as handle:
        for case in cases:
            source = case["source"]
            record = {
                "case_id": case["case_id"],
                "observation_cutoff": source["pull_request"]["created"],
                "source": {
                    "host": source["host"],
                    "repository": source["repository"],
                    "pull_request_number": source["pull_request"]["number"],
                    "subject": source["pull_request"]["subject"],
                    "base_commit": source["base_commit"],
                    "candidate_commit": source["candidate_commit"],
                    "changed_paths": source["changed_paths"],
                    "patch_url": source["patch_url"],
                },
                "candidate_repository_catalog": "candidate-repositories.json",
            }
            handle.write(json.dumps(record, ensure_ascii=False, sort_keys=True) + "\n")

    license_document = {
        "schema_version": "1.1",
        "note": "只发布元数据和链接；运行时取得的第三方源码仍受各仓库许可证约束。",
        "repositories": [licenses[key] for key in sorted(licenses)],
    }
    (ROOT / "licenses.json").write_text(
        json.dumps(license_document, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    summary = {
        "selected_cases": len(cases),
        "unique_source_repositories": len({case["source"]["repository"] for case in cases}),
        "unique_target_repositories": len({target["repository"] for case in cases for target in case["targets"]}),
        "unique_edges": len({(case["source"]["repository"], target["repository"]) for case in cases for target in case["targets"]}),
        "evidence_levels": Counter(
            evidence["level"]
            for case in cases
            for target in case["targets"]
            for evidence in target["evidence"]
        ),
        "impact_kinds": Counter(target["impact_kind"] for case in cases for target in case["targets"]),
        "label_scopes": Counter(target["label_scope"] for case in cases for target in case["targets"]),
        "raw_chain_independent_opendev_candidates": len(candidate_frame),
        "raw_opendev_source_candidates": raw_source_candidates,
        "raw_chain_overlapping_sources_removed": raw_source_candidates - len(candidate_frame),
        "chain_duplicate_sources_removed_before_sampling": chain_duplicates,
        "rejected": rejected,
    }
    (ROOT / "collection-summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--count", type=int, default=100)
    parser.add_argument("--max-pages", type=int, default=4)
    args = parser.parse_args()
    requested_open_dev = args.count - len(curated_ethereum_cases()) - 1
    fetch_count = requested_open_dev + max(30, requested_open_dev // 3)
    candidates, rejected, candidate_frame, raw_source_candidates = collect_candidates(
        args.max_pages, fetch_count
    )
    chain_independent, chain_duplicates = deduplicate_change_chains(candidates)
    reserved_numbers = {1000516, 1001023}
    chain_independent = [
        case for case in chain_independent
        if not (change_numbers(case) & reserved_numbers)
    ]
    cinder_case = curated_cinder_case()
    external_cases = curated_ethereum_cases()
    selected = systematic_sample(
        chain_independent,
        args.count - len(external_cases) - 1,
        required_case_ids={"opendev-1001388"},
    )
    apply_curated_execution_evidence(selected)
    selected.append(cinder_case)
    licenses = attach_licenses(selected)
    for case in external_cases:
        for license_record in case["licenses"]:
            licenses.setdefault(license_record["repository"], license_record)
    selected.extend(external_cases)
    selected.sort(key=lambda case: case["case_id"])
    write_dataset(
        selected,
        licenses,
        rejected,
        candidate_frame,
        chain_duplicates,
        raw_source_candidates,
    )
    print(
        f"wrote {len(selected)} cases from {len(candidates)} eligible OpenDev source changes; "
        f"removed {chain_duplicates} chain-overlapping source candidates before sampling"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
