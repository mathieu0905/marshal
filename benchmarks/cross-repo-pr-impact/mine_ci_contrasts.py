#!/usr/bin/env python3
"""Mine OpenDev patchset transitions that add Depends-On after a failing job."""

from __future__ import annotations

import argparse
import concurrent.futures
import json
import re
from pathlib import Path
from typing import Any

from collect_opendev import DEPENDS_RE, ROOT, gerrit_json


BUILD_RE = re.compile(
    r"^- (?P<job>.+?) https://zuul\.opendev\.org/(?:t/(?P<tenant>[^/]+)/)?build/"
    r"(?P<uuid>[0-9a-f]+) : (?P<result>[A-Z_]+)",
    re.MULTILINE,
)


def load_dependent_numbers() -> list[int]:
    numbers: set[int] = set()
    with (ROOT / "candidate-pool.jsonl").open(encoding="utf-8") as handle:
        for line in handle:
            if line.strip():
                numbers.update(json.loads(line)["target_prs"])
    return sorted(numbers)


def fetch_history(number: int) -> dict[str, Any]:
    return gerrit_json(
        f"/changes/{number}/detail",
        [("o", "ALL_REVISIONS"), ("o", "ALL_COMMITS"), ("o", "MESSAGES")],
    )


def revision_records(change: dict[str, Any]) -> list[dict[str, Any]]:
    records = []
    for sha, revision in change.get("revisions", {}).items():
        commit = revision.get("commit", {})
        message = commit.get("message", "")
        records.append({
            "number": int(revision["_number"]),
            "sha": sha,
            "created": revision.get("created"),
            "message": message,
            "depends_on": sorted({int(match.group(2)) for match in DEPENDS_RE.finditer(message)}),
        })
    return sorted(records, key=lambda item: item["number"])


def build_records(change: dict[str, Any], revision_number: int) -> list[dict[str, str]]:
    records = []
    for message in change.get("messages", []):
        if message.get("_revision_number") != revision_number:
            continue
        if message.get("tag") != "autogenerated:zuul:check":
            continue
        for match in BUILD_RE.finditer(message.get("message", "")):
            records.append(match.groupdict())
    return records


def mine_change(change: dict[str, Any]) -> list[dict[str, Any]]:
    revisions = revision_records(change)
    candidates = []
    for before, after in zip(revisions, revisions[1:]):
        added_dependencies = sorted(set(after["depends_on"]) - set(before["depends_on"]))
        if not added_dependencies:
            continue
        before_builds = build_records(change, before["number"])
        after_builds = build_records(change, after["number"])
        failures = {item["job"]: item for item in before_builds if item["result"] == "FAILURE"}
        successes = {item["job"]: item for item in after_builds if item["result"] == "SUCCESS"}
        common_jobs = sorted(failures.keys() & successes.keys())
        if not common_jobs:
            continue
        candidates.append({
            "source_repository": change["project"],
            "source_pr": int(change["_number"]),
            "source_created": change["created"],
            "source_subject": change["subject"],
            "before_revision": {
                "number": before["number"],
                "sha": before["sha"],
                "created": before["created"],
            },
            "after_revision": {
                "number": after["number"],
                "sha": after["sha"],
                "created": after["created"],
            },
            "added_dependency_prs": added_dependencies,
            "same_job_contrasts": [
                {
                    "job": job,
                    "tenant": failures[job]["tenant"] or successes[job]["tenant"],
                    "failure_build_uuid": failures[job]["uuid"],
                    "success_build_uuid": successes[job]["uuid"],
                }
                for job in common_jobs
            ],
        })
    return candidates


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=ROOT / "candidates" / "ci-contrast-candidates.jsonl",
    )
    parser.add_argument("--workers", type=int, default=12)
    parser.add_argument("--limit", type=int)
    args = parser.parse_args()

    numbers = load_dependent_numbers()
    if args.limit is not None:
        numbers = numbers[:args.limit]
    results = []
    failures = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=args.workers) as executor:
        futures = {executor.submit(fetch_history, number): number for number in numbers}
        for future in concurrent.futures.as_completed(futures):
            number = futures[future]
            try:
                results.extend(mine_change(future.result()))
            except Exception as exc:
                failures.append({"source_pr": number, "error": str(exc)})

    results.sort(key=lambda item: (item["source_created"], item["source_pr"]))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as handle:
        for item in results:
            handle.write(json.dumps(item, ensure_ascii=False, sort_keys=True) + "\n")
    failure_path = args.output.with_name("ci-contrast-fetch-failures.jsonl")
    with failure_path.open("w", encoding="utf-8") as handle:
        for item in sorted(failures, key=lambda row: row["source_pr"]):
            handle.write(json.dumps(item, ensure_ascii=False, sort_keys=True) + "\n")
    print(json.dumps({
        "changes_scanned": len(numbers),
        "contrast_candidates": len(results),
        "fetch_failures": len(failures),
        "output": str(args.output),
    }, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
